    def _generate_tee_key(self) -> str:
        """
        Generate private key using dstack getKey() in TEE environment
        Falls back to environment variable if not in TEE

        Returns:
            Private key as hex string (without 0x prefix)
        """
        if self.is_tee_environment:
            try:
                # Try to connect to dstack socket
                sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
                sock.settimeout(5.0)

                try:
                    sock.connect("/var/run/dstack.sock")
                    sock.send(b'getKey\n')
                    response = sock.recv(1024).decode().strip()

                    if response.startswith('0x'):
                        private_key = response[2:]
                    else:
                        private_key = response

                    # Validate the key
                    if len(private_key) == 64 and all(c in '0123456789abcdefABCDEF' for c in private_key):
                        print("✅ TEE private key generated successfully")
                        return private_key
                    else:
                        raise ValueError(f"Invalid private key format from dstack: {response}")

                except Exception as e:
                    print(f"⚠️ dstack socket connection failed: {e}")
                    # Fall back to legacy method
                    try:
                        sock.connect("/var/run/tappd.sock")
                        sock.send(b'getKey\n')
                        response = sock.recv(1024).decode().strip()

                        if response.startswith('0x'):
                            private_key = response[2:]
                        else:
                            private_key = response

                        if len(private_key) == 64 and all(c in '0123456789abcdefABCDEF' for c in private_key):
                            print("✅ Legacy TEE private key generated successfully")
                            return private_key
                        else:
                            raise ValueError(f"Invalid private key format from legacy TEE: {response}")

                    except Exception as legacy_e:
                        print(f"❌ All TEE key generation methods failed: {legacy_e}")
                        raise Exception("TEE key generation failed - are you in a TEE environment?")

            except Exception as e:
                print(f"❌ TEE key generation failed: {e}")
                raise Exception("TEE key generation failed - are you in a TEE environment?")
        else:
            # Fallback to environment variable for non-TEE environments
            private_key = os.getenv('PRIVATE_KEY')
            if not private_key:
                raise Exception(
                    "No private key provided and not in TEE environment. "
                    "Set PRIVATE_KEY environment variable or run in Phala TEE."
                )

            # Clean the private key
            if private_key.startswith('0x'):
                private_key = private_key[2:]

            return private_key

    def _detect_tee_environment(self) -> bool:
        """
        Detect if we're running in a TEE environment

        Returns:
            True if in TEE environment, False otherwise
        """
        # Check environment variables
        if os.getenv('TEE_MODE') == 'production':
            return True

        if os.getenv('PHALA_DEPLOYMENT') == 'true':
            return True

        # Check for dstack socket
        if os.path.exists('/var/run/dstack.sock'):
            return True

        # Check for legacy TEE socket
        if os.path.exists('/var/run/tappd.sock'):
            return True

        # Check if we're in a container with TEE simulation
        if os.getenv('TEE_SIMULATION_MODE') == 'true':
            return True

        return False

